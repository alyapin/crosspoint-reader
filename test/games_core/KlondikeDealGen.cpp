// Prints lib/Games/KlondikeDeals.h: build/test/games_core/KlondikeDealGen > lib/Games/KlondikeDeals.h
#include <chrono>
#include <cstdio>
#include <vector>

#include "KlondikeSolver.h"

namespace {

constexpr int PER_MODE = 256;
constexpr uint32_t NODE_LIMIT = 200000;

void emit(const bool drawThree) {
  std::vector<klondike::SolverStep> line;
  std::vector<uint32_t> seeds;
  int tried = 0;
  const auto t0 = std::chrono::steady_clock::now();
  for (uint32_t seed = drawThree ? 3000001u : 1000001u; static_cast<int>(seeds.size()) < PER_MODE; ++seed) {
    uint8_t deck[klondike::DECK];
    klondike::shuffledDeck(seed, deck);
    klondike::Board board;
    klondike::deal(board, deck);
    ++tried;
    if (klondike::solve(board, drawThree, NODE_LIMIT, line)) seeds.push_back(seed);
  }
  const double s = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
  fprintf(stderr, "draw %d: %d of %d deals solved within %u nodes, %.1f s\n", drawThree ? 3 : 1, PER_MODE, tried,
          NODE_LIMIT, s);
  printf("constexpr int SOLVABLE_DRAW%d_COUNT = %d;\n", drawThree ? 3 : 1, PER_MODE);
  printf("constexpr uint32_t SOLVABLE_DRAW%d[SOLVABLE_DRAW%d_COUNT] = {", drawThree ? 3 : 1, drawThree ? 3 : 1);
  for (size_t i = 0; i < seeds.size(); ++i) printf("%s%u,", i % 13 == 0 ? "\n    " : " ", seeds[i]);
  printf("\n};\n\n");
}

}  // namespace

int main() {
  printf(
      "#pragma once\n\n"
      "// Generated by test/games_core/KlondikeDealGen.cpp: shuffledDeck() seeds whose deals the\n"
      "// host solver won (all cards known). Host-tested by replaying solver lines through Game.\n\n"
      "#include <cstdint>\n\n"
      "namespace klondike {\n\n");
  emit(false);
  emit(true);
  printf("}  // namespace klondike\n");
  return 0;
}
