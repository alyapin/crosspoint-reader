"""Hangman word list: common nouns with a short definition, packed into a C++ header.

    python3 -I tools/hangman/gen_words.py LEXICON.tsv lib/Games/HangmanWords.h [--max-bytes 40000]

LEXICON.tsv is the scanword lexicon (word, Zipf frequency, clue, clue kind) that
tools/scanword/lexicon.py builds. Words of 5-10 letters with a dictionary
definition are taken most frequent first until the packed data reaches
--max-bytes. One byte per letter: lib/Games/Hangman.h ALPHABET.
"""

import argparse
import sys
from pathlib import Path

ALPHABET_RU = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
ALPHABET = "abvgdeEjziyklmnoprstufhcCwWXYxqUQ"  # must match lib/Games/Hangman.h
CODE = dict(zip(ALPHABET_RU, ALPHABET))
MIN_LEN, MAX_LEN = 5, 10
MAX_CLUE = 26  # characters; the clue column wraps it to two or three lines


def encode(text):
    return "".join(CODE.get(ch, ch) for ch in text)


def usable(word, clue, kind):
    if (
        kind != "def"
        or not MIN_LEN <= len(word) <= MAX_LEN
        or not 0 < len(clue) <= MAX_CLUE
    ):
        return False
    if any(ch not in CODE for ch in word) or clue[0].lower() not in CODE:
        return False
    # Only the first letter of a definition is a capital, and it is implied.
    if any(ch not in CODE and ch not in " -" for ch in clue[1:]):
        return False
    # A definition that spells the word out gives it away.
    return word[:4] not in clue.lower()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("lexicon", type=Path)
    parser.add_argument("out", type=Path)
    parser.add_argument("--max-bytes", type=int, default=40000)
    args = parser.parse_args()

    entries = []
    for line in args.lexicon.read_text(encoding="utf-8").splitlines():
        word, zipf, clue, kind = line.split("\t")
        if usable(word, clue, kind):
            entries.append((float(zipf), word, clue))
    entries.sort(key=lambda e: (-e[0], e[1]))

    lines, size = [], 0
    for _, word, clue in entries:
        line = f"{encode(word)}:{encode(clue.lower())}"
        if size + len(line) + 1 > args.max_bytes:
            break
        lines.append(line)
        size += len(line) + 1
    if len(lines) > 0xFFFF:
        sys.exit("too many words")

    body = "\n".join(f'    "{line}\\n"' for line in lines)
    args.out.write_text(
        f"""#pragma once

// Generated by tools/hangman/gen_words.py; regenerate from the repository root with
//   python3 -I tools/hangman/gen_words.py LEXICON.tsv {args.out.as_posix()}
// Words and definitions derived from the Russian Wiktionary (https://ru.wiktionary.org), CC BY-SA 4.0;
// see tools/hangman/ATTRIBUTION.txt.

#include <cstdint>

namespace hangman {{

constexpr uint16_t WORD_COUNT = {len(lines)};

// "word:definition\\n" per word, most frequent first, in ALPHABET; the definition starts with a capital.
constexpr char WORDS[] =
{body};

}}  // namespace hangman
""",
        encoding="utf-8",
    )
    print(f"{len(lines)} words, {size} bytes", file=sys.stderr)


if __name__ == "__main__":
    main()
